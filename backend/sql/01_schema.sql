-- ==========================================================
-- Oracle Database ERP System Schema
-- Modules: Inventory/Products, Suppliers, Customers, Sales Orders
-- Compatible with Oracle DB 19c, 21c, 23ai (Free / XE / EE)
-- ==========================================================

-- Drop existing tables safely
BEGIN
   FOR cur_rec IN (SELECT table_name FROM user_tables WHERE table_name IN ('ORDER_ITEMS', 'SALES_ORDERS', 'ITEMS', 'CUSTOMERS', 'SUPPLIERS')) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || cur_rec.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
END;
/

-- 1. Suppliers / Vendors Table
CREATE TABLE suppliers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    code VARCHAR2(50) UNIQUE NOT NULL,
    contact_person VARCHAR2(100),
    email VARCHAR2(100),
    phone VARCHAR2(50),
    city VARCHAR2(100),
    payment_terms VARCHAR2(50) DEFAULT 'Net 30',
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Customers / Clients Table
CREATE TABLE customers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    customer_code VARCHAR2(50) UNIQUE NOT NULL,
    contact_person VARCHAR2(100),
    email VARCHAR2(100),
    phone VARCHAR2(50),
    city VARCHAR2(100),
    credit_limit NUMBER(12, 2) DEFAULT 50000.00,
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. Products / Inventory Items Table
CREATE TABLE items (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    sku VARCHAR2(50) UNIQUE NOT NULL,
    category VARCHAR2(100) NOT NULL,
    unit_of_measure VARCHAR2(20) DEFAULT 'PCS',
    cost_price NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    stock_quantity NUMBER(8) DEFAULT 0 NOT NULL,
    reorder_level NUMBER(8) DEFAULT 10 NOT NULL,
    supplier_id NUMBER REFERENCES suppliers(id) ON DELETE SET NULL,
    description VARCHAR2(500),
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'OUT_OF_STOCK')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_items_category ON items(category);
CREATE INDEX idx_items_status ON items(status);

-- 4. Sales Orders Table
CREATE TABLE sales_orders (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR2(50) UNIQUE NOT NULL,
    customer_id NUMBER NOT NULL REFERENCES customers(id),
    order_date DATE DEFAULT SYSDATE NOT NULL,
    due_date DATE,
    total_amount NUMBER(12, 2) DEFAULT 0.00 NOT NULL,
    status VARCHAR2(20) DEFAULT 'PENDING' CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'PROCESSING', 'SHIPPED', 'COMPLETED', 'CANCELLED')),
    payment_status VARCHAR2(20) DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID', 'PARTIAL', 'PAID')),
    notes VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_so_customer ON sales_orders(customer_id);
CREATE INDEX idx_so_status ON sales_orders(status);

-- 5. Order Line Items Table
CREATE TABLE order_items (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
    item_id NUMBER NOT NULL REFERENCES items(id),
    quantity NUMBER(8) NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    subtotal NUMBER(12, 2) NOT NULL
);

-- Triggers for auto timestamp updates
CREATE OR REPLACE TRIGGER trg_items_updated_at
BEFORE UPDATE ON items
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_orders_updated_at
BEFORE UPDATE ON sales_orders
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

COMMIT;
