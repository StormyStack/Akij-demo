-- ==========================================================
-- Oracle Database 3-Tier Demo Schema
-- Table: ITEMS (Product / Inventory PoC)
-- Compatible with Oracle DB 19c, 21c, 23ai (Free / XE / EE)
-- ==========================================================

-- Drop table if already exists (safe for clean re-runs)
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE items CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -942 THEN
         RAISE;
      END IF;
END;
/

-- Create Table with Identity column
CREATE TABLE items (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    sku VARCHAR2(50) UNIQUE NOT NULL,
    category VARCHAR2(100) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    stock_quantity NUMBER(8) DEFAULT 0 NOT NULL,
    description VARCHAR2(500),
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'OUT_OF_STOCK')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Index for fast searches by category and status
CREATE INDEX idx_items_category ON items(category);
CREATE INDEX idx_items_status ON items(status);

-- Trigger to update updated_at on record modification
CREATE OR REPLACE TRIGGER trg_items_updated_at
BEFORE UPDATE ON items
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

COMMIT;
