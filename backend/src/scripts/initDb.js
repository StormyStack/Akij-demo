const fs = require('fs');
const path = require('path');
const oracledb = require('oracledb');
require('dotenv').config({ path: path.join(__dirname, '../../.env') });

async function runInitScripts() {
  const dbConfig = {
    user: process.env.ORACLE_USER || 'poc_user',
    password: process.env.ORACLE_PASSWORD || 'poc_password',
    connectString: process.env.ORACLE_CONNECT_STRING || 'localhost:1521/FREEPDB1',
  };

  console.log(`[ERP DB Init] Connecting to Oracle Database at ${dbConfig.connectString}...`);
  let connection;

  try {
    connection = await oracledb.getConnection(dbConfig);
    console.log('[ERP DB Init] Connected successfully! Checking existing ERP tables...');

    const tablesCheck = await connection.execute(
      "SELECT table_name FROM user_tables WHERE table_name IN ('ITEMS', 'SALES_ORDERS', 'CUSTOMERS', 'SUPPLIERS')"
    );

    const existingTables = (tablesCheck.rows || []).map(r => r[0] || r.TABLE_NAME);
    console.log(`[ERP DB Init] Existing tables found: ${existingTables.join(', ') || 'None'}`);

    // Ensure items table has image_url column for Azure Blob assets
    try {
      await connection.execute(`
        BEGIN
          EXECUTE IMMEDIATE 'ALTER TABLE items ADD (image_url VARCHAR2(1000))';
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
      `);
      console.log('[ERP DB Init] items.image_url column verified/added.');
    } catch (colErr) {
      console.warn('[ERP DB Init] Notice on items.image_url check:', colErr.message);
    }

    if (existingTables.length < 4) {
      console.log('[ERP DB Init] Creating relational ERP schema...');

      // 1. Suppliers
      await connection.execute(`
        BEGIN
          EXECUTE IMMEDIATE '
            CREATE TABLE suppliers (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(150) NOT NULL,
                code VARCHAR2(50) UNIQUE NOT NULL,
                contact_person VARCHAR2(100),
                email VARCHAR2(100),
                phone VARCHAR2(50),
                city VARCHAR2(100),
                payment_terms VARCHAR2(50) DEFAULT ''Net 30'',
                status VARCHAR2(20) DEFAULT ''ACTIVE'',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
          ';
        EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
        END;
      `);

      // 2. Customers
      await connection.execute(`
        BEGIN
          EXECUTE IMMEDIATE '
            CREATE TABLE customers (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(150) NOT NULL,
                customer_code VARCHAR2(50) UNIQUE NOT NULL,
                contact_person VARCHAR2(100),
                email VARCHAR2(100),
                phone VARCHAR2(50),
                city VARCHAR2(100),
                credit_limit NUMBER(12, 2) DEFAULT 50000.00,
                status VARCHAR2(20) DEFAULT ''ACTIVE'',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
          ';
        EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
        END;
      `);

      // 3. Items / Products
      await connection.execute(`
        BEGIN
          EXECUTE IMMEDIATE '
            CREATE TABLE items (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(150) NOT NULL,
                sku VARCHAR2(50) UNIQUE NOT NULL,
                category VARCHAR2(100) NOT NULL,
                unit_of_measure VARCHAR2(20) DEFAULT ''PCS'',
                cost_price NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
                price NUMBER(10, 2) NOT NULL,
                stock_quantity NUMBER(8) DEFAULT 0 NOT NULL,
                reorder_level NUMBER(8) DEFAULT 10 NOT NULL,
                supplier_id NUMBER,
                description VARCHAR2(500),
                status VARCHAR2(20) DEFAULT ''ACTIVE'',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
          ';
        EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
        END;
      `);

      // 4. Sales Orders
      await connection.execute(`
        BEGIN
          EXECUTE IMMEDIATE '
            CREATE TABLE sales_orders (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_number VARCHAR2(50) UNIQUE NOT NULL,
                customer_id NUMBER NOT NULL,
                order_date DATE DEFAULT SYSDATE NOT NULL,
                due_date DATE,
                total_amount NUMBER(12, 2) DEFAULT 0.00 NOT NULL,
                status VARCHAR2(20) DEFAULT ''PENDING'',
                payment_status VARCHAR2(20) DEFAULT ''UNPAID'',
                notes VARCHAR2(500),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
          ';
        EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
        END;
      `);

      console.log('[ERP DB Init] Schema tables ready. Seeding demo ERP records...');

      // Seed Suppliers
      await connection.execute(`
        INSERT INTO suppliers (name, code, contact_person, email, phone, city, payment_terms, status)
        VALUES ('Apex Industrial Supplies Ltd', 'SUP-001', 'Rafiqul Islam', 'rafiqul@apexindustrial.com', '+880-1711-223344', 'Dhaka', 'Net 30', 'ACTIVE')
      `, [], { autoCommit: true });

      // Seed Customers
      await connection.execute(`
        INSERT INTO customers (name, customer_code, contact_person, email, phone, city, credit_limit, status)
        VALUES ('Dhaka Logistics & Distribution', 'CUST-101', 'Kamrul Hasan', 'kamrul@dhakalogistics.com', '+880-1715-998877', 'Dhaka', 75000.00, 'ACTIVE')
      `, [], { autoCommit: true });

      // Seed Items
      await connection.execute(`
        INSERT INTO items (name, sku, category, unit_of_measure, cost_price, price, stock_quantity, reorder_level, description, status)
        VALUES ('Heavy Duty Industrial Motor 5HP', 'PRD-MTR-5HP', 'Machinery', 'UNIT', 450.00, 680.00, 24, 8, 'Three-phase 5HP AC induction motor', 'ACTIVE')
      `, [], { autoCommit: true });

      await connection.execute(`
        INSERT INTO items (name, sku, category, unit_of_measure, cost_price, price, stock_quantity, reorder_level, description, status)
        VALUES ('Corrugated Shipping Cartons (500 Pack)', 'PRD-BOX-500', 'Packaging', 'BUNDLE', 120.00, 185.00, 150, 40, 'Heavy duty export packaging boxes', 'ACTIVE')
      `, [], { autoCommit: true });

      // Seed Order
      await connection.execute(`
        INSERT INTO sales_orders (order_number, customer_id, total_amount, status, payment_status, notes)
        VALUES ('SO-2026-001', 1, 4260.00, 'APPROVED', 'PAID', 'Priority dispatch for warehouse expansion')
      `, [], { autoCommit: true });

      console.log('[ERP DB Init] Seed data inserted successfully!');
    }

    console.log('[ERP DB Init] Complete.');
  } catch (err) {
    console.error('[ERP DB Init] Error:', err.message);
  } finally {
    if (connection) {
      try { await connection.close(); } catch (e) { /* ignore */ }
    }
  }
}

if (require.main === module) {
  runInitScripts().then(() => process.exit(0));
}

module.exports = { runInitScripts };
