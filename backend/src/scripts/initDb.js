const fs = require('fs');
const path = require('path');
const oracledb = require('oracledb');
require('dotenv').config({ path: path.join(__dirname, '../../.env') });

async function runInitScripts() {
  const dbConfig = {
    user: process.env.ORACLE_USER || 'poc_user',
    password: process.env.ORACLE_PASSWORD || 'poc_password',
    connectString: process.env.ORACLE_CONNECT_STRING || 'localhost:1521/FREEPDB1',
  };

  console.log(`[DB Init] Connecting to Oracle Database at ${dbConfig.connectString}...`);
  let connection;

  try {
    connection = await oracledb.getConnection(dbConfig);
    console.log('[DB Init] Connected successfully! Checking existing tables...');

    // Check if items table exists
    const checkTableResult = await connection.execute(
      "SELECT table_name FROM user_tables WHERE table_name = 'ITEMS'"
    );

    if (checkTableResult.rows && checkTableResult.rows.length > 0) {
      console.log('[DB Init] Table ITEMS already exists.');
    } else {
      console.log('[DB Init] Creating ITEMS table...');
      const schemaSql = `
        CREATE TABLE items (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR2(150) NOT NULL,
            sku VARCHAR2(50) UNIQUE NOT NULL,
            category VARCHAR2(100) NOT NULL,
            price NUMBER(10, 2) NOT NULL,
            stock_quantity NUMBER(8) DEFAULT 0 NOT NULL,
            description VARCHAR2(500),
            status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'OUT_OF_STOCK')),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
        )
      `;
      await connection.execute(schemaSql);
      console.log('[DB Init] Table ITEMS created successfully!');

      console.log('[DB Init] Seeding initial demo data...');
      const seeds = [
        ["Dell UltraSharp 27\" 4K Monitor", "MON-DEL-4K27", "Electronics", 449.99, 28, "4K UHD IPS display with USB-C Hub", "ACTIVE"],
        ["Logitech MX Master 3S Wireless Mouse", "ACC-LOG-MX3S", "Accessories", 99.99, 65, "Quiet clicks with 8K DPI sensor", "ACTIVE"],
        ["Keychron Q1 Pro Mechanical Keyboard", "KEY-KCH-Q1P", "Peripherals", 199.00, 18, "Custom wireless QMK/VIA gasket-mounted", "ACTIVE"],
        ["Sony WH-1000XM5 Noise Canceling Headphones", "AUD-SNY-XM5", "Audio", 398.00, 42, "Industry leading noise cancellation", "ACTIVE"],
        ["Ergonomic Mesh Office Chair", "FUR-ERG-OC01", "Furniture", 320.50, 15, "Breathable mesh high-back chair", "ACTIVE"],
        ["Electric Standing Desk 60x30", "FUR-DSK-ESD60", "Furniture", 540.00, 8, "Dual-motor motorized standing desk", "ACTIVE"]
      ];

      for (const row of seeds) {
        await connection.execute(
          `INSERT INTO items (name, sku, category, price, stock_quantity, description, status) 
           VALUES (:1, :2, :3, :4, :5, :6, :7)`,
          row,
          { autoCommit: true }
        );
      }
      console.log(`[DB Init] Seeded ${seeds.length} demo records into ITEMS!`);
    }

    console.log('[DB Init] Database initialization complete.');
  } catch (err) {
    console.error('[DB Init] Error during database initialization:', err.message);
  } finally {
    if (connection) {
      try {
        await connection.close();
      } catch (err) {
        console.error(err);
      }
    }
  }
}

if (require.main === module) {
  runInitScripts().then(() => process.exit(0));
}

module.exports = { runInitScripts };
